import { useEffect } from 'react';
import MainContextProvider from '@/context/MainContextProvider';
import LanguageServiceProvider from '@/context/LanguageServiceProvider';
import GameContextProvider from '@/context/GameContextProvider';
import ScriptsProvider from '@/context/ScriptsProvider';
import { useLanguageServiceContext } from '@/context/LanguageServiceContext';
import { loadDraft } from '@/lib/storage';
import { PRESETS } from '@/presets';
import Header from './layout/Header';
import Sidebar from './sidebar/Sidebar';
import EditorPane from './editor/EditorPane';
import StagePanel from './stage/StagePanel';

/** Start Code Generated by Claude on 2026-11-25 */
const draft = loadDraft();
const starter = PRESETS[0];
const initial = draft ?? { name: starter.name, source: starter.source, scriptId: null };

function RunOnStart() {
  const { compile } = useLanguageServiceContext();
  useEffect(() => {
    // Give the workers a moment to boot, then run whatever is in the editor.
    const handle = setTimeout(compile, 50);
    return () => clearTimeout(handle);
  }, [compile]);
  return null;
}

function App() {
  return (
    <MainContextProvider>
      <LanguageServiceProvider initialText={initial.source}>
        <ScriptsProvider initialName={initial.name} initialScriptId={initial.scriptId}>
          <GameContextProvider>
            <RunOnStart />
            <div className="flex h-dvh flex-col">
              <Header />
              <main className="app-grid min-h-0 flex-1">
                <Sidebar />
                <EditorPane />
                <StagePanel />
              </main>
            </div>
          </GameContextProvider>
        </ScriptsProvider>
      </LanguageServiceProvider>
    </MainContextProvider>
  );
}
/** End Code Generated by Claude on 2026-11-25 */

export default App;
