export type Segment = { text: string; category: TokenCategory };

/**
 * Splits source into coloured segments. Text the lexer skips (comments) is
 * kept, so the highlight layer always lines up with the textarea.
 */
export function segment(source: string, tokens: Token[]): Segment[] {
  const out: Segment[] = [];
  let cursor = 0;
  const pushGap = (end: number) => {
    if (end <= cursor) return;
    const gap = source.slice(cursor, end);
    for (const piece of gap.split(/(#[^\n]*)/)) {
      if (piece) out.push({ text: piece, category: piece.startsWith('#') ? 'comment' : 'plain' });
    }
  };
  for (const token of tokens) {
    if (token.start < cursor || token.stop < token.start) continue;
    pushGap(token.start);
    out.push({
      text: source.slice(token.start, token.stop + 1),
      category: TOKEN_CATEGORIES[token.type] ?? 'plain',
    });
    cursor = token.stop + 1;
  }
  pushGap(source.length);
  return out;
}
